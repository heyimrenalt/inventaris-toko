  };
}

/// Thrown by [assertSafeSeedDirectory] when a seed target would land on
/// the production database.
class UnsafeSeedDirectoryError extends Error {
  UnsafeSeedDirectoryError(this.message);

  final String message;

  @override
  String toString() => 'UnsafeSeedDirectoryError: $message';
}

/// Refuses any seed directory that is — or sits inside — the app's real
/// documents directory, which is where `IsarService.open()` puts the
/// production database.
///
/// This is the hard stop that makes the scale test safe to run on a phone
/// that has the real app installed: the seeder calls it with the directory
/// it is about to open *before* opening anything, so a mistake fails loudly
/// instead of quietly writing 1000 rows into the shop's real ledger.
///
/// Comparison is on normalised, separator-terminated paths so
/// `/data/.../documents_seed` isn't mistaken for a child of
/// `/data/.../documents`.
void assertSafeSeedDirectory({
  required String seedDirectory,
  required String productionDirectory,
}) {
  final seed = _normalise(seedDirectory);
  final production = _normalise(productionDirectory);

  if (seed == production) {
    throw UnsafeSeedDirectoryError(
      'Refusing to seed into the production database directory '
      '($seedDirectory).',
    );
  }
  if (seed.startsWith(production)) {
    throw UnsafeSeedDirectoryError(
      'Refusing to seed into $seedDirectory: it is inside the production '
      'database directory ($productionDirectory).',
    );
  }
}

/// Trailing-separator-terminated form, so prefix comparison can only match
/// on a whole path segment.
String _normalise(String path) {
  var normalised = path.replaceAll('\\', '/');
  while (normalised.endsWith('/')) {
    normalised = normalised.substring(0, normalised.length - 1);
  }
  return '$normalised/';
}
