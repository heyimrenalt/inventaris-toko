/// Report-only wall-clock timings, printed once at the end of the run. These
/// are never asserted on — a shared CI machine's timing is not a contract —
/// they exist so a restore that becomes pathologically slow is at least
/// visible in the test output.
class _Timings {
  final Map<String, List<int>> _millisByLabel = {};

  Future<T> measure<T>(String label, Future<T> Function() body) async {
    final stopwatch = Stopwatch()..start();
    final result = await body();
    stopwatch.stop();
    _millisByLabel.putIfAbsent(label, () => []).add(stopwatch.elapsedMilliseconds);
    return result;
  }

  void printTable() {
    if (_millisByLabel.isEmpty) return;
    final width = _millisByLabel.keys.map((k) => k.length).reduce((a, b) => a > b ? a : b);
    // ignore: avoid_print
    print('\n${'Backup/restore integrity timings (report only)'.padRight(width)}   n     avg ms');
    for (final entry in _millisByLabel.entries) {
      final avg = entry.value.reduce((a, b) => a + b) / entry.value.length;
      // ignore: avoid_print
      print('${entry.key.padRight(width)}   ${entry.value.length.toString().padLeft(3)}   '
          '${avg.toStringAsFixed(1).padLeft(8)}');
    }
  }
}
